#!/bin/bash
# GNOME loads stylesheet-light.css instead of stylesheet.css when the shell
# is light. The top bar stays dark in both (Adwaita and Yaru), but menus turn
# light: the popup's white tints become black ones. Everything from the
# "the popup" section on is converted; the pill above it is kept as is.
#
#   tools/gen-light-css.sh

set -euo pipefail

root=$(cd -- "$(dirname -- "$0")/.." && pwd)
src=$root/nowbar@vinicgobbi.dev.br/stylesheet.css
out=$root/nowbar@vinicgobbi.dev.br/stylesheet-light.css

grep -q '^/\* --- the popup' "$src" || { echo "gen-light-css: no popup section marker in $src" >&2; exit 1; }

{
  echo "/* Generated by tools/gen-light-css.sh from stylesheet.css: edit that one. */"
  echo
  awk '/^\/\* --- the popup/ { popup = 1 }
       popup { gsub(/rgba\(255, 255, 255,/, "rgba(0, 0, 0,") }
       { print }' "$src"
} > "$out"

echo "gen-light-css: wrote $out"
