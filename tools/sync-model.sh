#!/bin/bash
# Copies NowbarModel.js (the pure logic shared with omarchy-plugin-nowbar)
# into the extension as an ES module: the file is kept as is, and every
# top-level function and var is exported at the end.
#
#   tools/sync-model.sh [path/to/NowbarModel.js]

set -euo pipefail

root=$(cd -- "$(dirname -- "$0")/.." && pwd)
src=${1:-$root/../omarchy-plugin-nowbar/NowbarModel.js}
out=$root/nowbar@vinicgobbi.dev.br/lib/model.js

[[ -f $src ]] || { echo "sync-model: $src not found" >&2; exit 1; }

names=$(grep -oE '^(function|var) [A-Za-z_][A-Za-z0-9_]*' "$src" | awk '{print $2}' | sort -u | paste -sd, - | sed 's/,/, /g')

{
  echo "// Generated by tools/sync-model.sh from omarchy-plugin-nowbar's NowbarModel.js."
  echo "// Edit the original and run the script again."
  echo
  cat "$src"
  echo
  echo "export { $names }"
} > "$out"

echo "sync-model: wrote $out"
